export function t(key, lang = 'es') {
  return translations[lang]?.[key] || translations['es']?.[key] || key;
}

// Igual que t() pero reemplaza placeholders {nombre} con valores, ej:
// tf('common-delete-confirm', lang, { name: 'Noruega' })
export function tf(key, lang, vars = {}) {
  return t(key, lang).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
